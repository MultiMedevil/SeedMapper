#!/usr/bin/env python3
"""Generates mansion_templates.h from the vanilla woodland mansion structure templates.

Usage:
    python3 _gen_mansion_templates.py <path/to/data/minecraft/structure/woodland_mansion> > ../mansion_templates.h

The directory is the one found in the vanilla server/client jar. Only the room
templates (the ones whose file name starts with a digit) matter for loot: none of
the wall, roof, carpet or entrance templates contains a container or data marker.

For every room template this script records, in the exact order in which vanilla
iterates over them (blocks carrying NBT are sorted by y, then x, then z when a
template is loaded):

  * "containers": blocks whose block entity is a RandomizableContainer (chests and
    trapped chests with fixed contents). StructureTemplate#placeInWorld draws one
    nextLong() from the decoration random for each of them, even though they do
    not have a loot table.
  * "chests": structure blocks in DATA mode whose metadata starts with "Chest".
    WoodlandMansionPiece#handleDataMarker turns each of them into a chest with the
    loot table chests/woodland_mansion and a loot seed taken from the same random.

The script does not depend on anything outside the Python standard library.
"""
import gzip
import io
import os
import struct
import sys

# block ids whose block entity implements RandomizableContainer
RANDOMIZABLE_CONTAINERS = {
    'minecraft:chest', 'minecraft:trapped_chest', 'minecraft:barrel', 'minecraft:dispenser',
    'minecraft:dropper', 'minecraft:hopper', 'minecraft:crafter', 'minecraft:decorated_pot',
}


def _read(f, fmt):
    return struct.unpack(fmt, f.read(struct.calcsize(fmt)))[0]


def _string(f):
    return f.read(_read(f, '>H')).decode('utf-8', 'replace')


def _payload(f, tag):
    if tag == 1: return _read(f, '>b')
    if tag == 2: return _read(f, '>h')
    if tag == 3: return _read(f, '>i')
    if tag == 4: return _read(f, '>q')
    if tag == 5: return _read(f, '>f')
    if tag == 6: return _read(f, '>d')
    if tag == 7: return list(f.read(_read(f, '>i')))
    if tag == 8: return _string(f)
    if tag == 9:
        element = _read(f, '>b')
        return [_payload(f, element) for _ in range(_read(f, '>i'))]
    if tag == 10:
        compound = {}
        while True:
            child = _read(f, '>b')
            if child == 0:
                return compound
            name = _string(f)
            compound[name] = _payload(f, child)
    if tag == 11: return [_read(f, '>i') for _ in range(_read(f, '>i'))]
    if tag == 12: return [_read(f, '>q') for _ in range(_read(f, '>i'))]
    raise ValueError('unknown NBT tag %d' % tag)


def load_nbt(path):
    with open(path, 'rb') as fh:
        raw = fh.read()
    if raw[:2] == b'\x1f\x8b':
        raw = gzip.decompress(raw)
    f = io.BytesIO(raw)
    tag = _read(f, '>b')
    _string(f)
    return _payload(f, tag)


def main():
    directory = sys.argv[1]
    names = sorted(fn[:-4] for fn in os.listdir(directory) if fn.endswith('.nbt') and fn[0].isdigit())
    templates = []
    for name in names:
        template = load_nbt(os.path.join(directory, name + '.nbt'))
        palette = template['palette']
        containers, chests = [], []
        for block in template['blocks']:
            if 'nbt' not in block:
                continue
            state = palette[block['state']]
            block_id = state.get('Name', state.get('id'))
            x, y, z = block['pos']
            if block_id == 'minecraft:structure_block':
                if block['nbt'].get('mode') == 'DATA' and block['nbt'].get('metadata', '').startswith('Chest'):
                    chests.append((y, x, z))
            elif block_id in RANDOMIZABLE_CONTAINERS:
                if 'LootTable' in block['nbt']:
                    raise ValueError('%s: container with a loot table, not handled' % name)
                containers.append((y, x, z))
        containers.sort()
        chests.sort()
        templates.append((name, template['size'], containers, chests))

    out = []
    out.append('// Generated by features/mansion/_gen_mansion_templates.py from the vanilla structure templates.')
    out.append('// Do not edit by hand.')
    out.append('#ifndef MANSION_TEMPLATES_H_')
    out.append('#define MANSION_TEMPLATES_H_')
    out.append('')
    out.append('#include <stdint.h>')
    out.append('')
    out.append('typedef struct { int8_t x, y, z; } MansionTemplatePos;')
    out.append('')
    out.append('typedef struct {')
    out.append('    const char *name;                     // template path below structure/')
    out.append('    uint8_t sx, sy, sz;                   // template size')
    out.append('    uint8_t containerCount;               // fixed containers that consume one nextLong() each')
    out.append('    uint8_t chestCount;                   // loot chest data markers')
    out.append('    const MansionTemplatePos *containers; // in vanilla iteration order (y, x, z)')
    out.append('    const MansionTemplatePos *chests;     // in vanilla iteration order (y, x, z)')
    out.append('} MansionTemplate;')
    out.append('')
    out.append('enum MansionRoomTemplate {')
    for i, (name, _, _, _) in enumerate(templates):
        out.append('    MANSION_%s = %d,' % (name.upper(), i))
    out.append('    MANSION_ROOM_TEMPLATE_COUNT = %d' % len(templates))
    out.append('};')
    out.append('')
    for name, _, containers, chests in templates:
        for kind, positions in (('containers', containers), ('chests', chests)):
            if positions:
                body = ', '.join('{%d, %d, %d}' % (x, y, z) for (y, x, z) in positions)
                out.append('static const MansionTemplatePos mansion_%s_%s[] = {%s};' % (name, kind, body))
    out.append('')
    out.append('static const MansionTemplate g_mansion_templates[MANSION_ROOM_TEMPLATE_COUNT] = {')
    for name, size, containers, chests in templates:
        out.append('    {"woodland_mansion/%s", %d, %d, %d, %d, %d, %s, %s},' % (
            name, size[0], size[1], size[2], len(containers), len(chests),
            ('mansion_%s_containers' % name) if containers else '0',
            ('mansion_%s_chests' % name) if chests else '0'))
    out.append('};')
    out.append('')
    out.append('#endif // MANSION_TEMPLATES_H_')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
